#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::Value;

    fn sample() -> Vec<u8> {
        let mut d = vec![0u8; SIZE];
        for i in 0..9 {
            d[CHARS + i * STRIDE] = 10 + i as u8;
        }
        d[0x14..0x18].copy_from_slice(&5000u32.to_le_bytes());
        d[0x1D0..0x1D4].copy_from_slice(&5000u32.to_le_bytes());
        d[ITEMS] = 7;
        d
    }

    #[test]
    fn reads_and_writes_in_place() {
        let d = sample();
        assert!(looks(&d));
        let mut doc = parse(&d).unwrap();
        assert_eq!(doc.view.pointer("/Party/Gald").unwrap(), &Value::from(5000));
        assert_eq!(doc.view.pointer("/Characters/Colette/Level").unwrap(), &Value::from(11));
        assert_eq!(doc.view.pointer("/Items/Apple Gel").unwrap(), &Value::from(7));
        assert_eq!(doc.to_bytes().unwrap(), d);
        doc.set("/Party/Gald", Value::from(123_456)).unwrap();
        doc.set("/Characters/Lloyd/Level", Value::from(200)).unwrap();
        let out = doc.to_bytes().unwrap();
        assert_eq!(u32_at(&out, 0x14), 123_456);
        assert_eq!(u32_at(&out, 0x1D0), 123_456, "the copy follows");
        assert_eq!(out[CHARS], 200);
        assert_eq!(out.len(), SIZE);
    }

    #[test]
    fn other_files_are_refused() {
        assert!(!looks(&vec![0u8; SIZE]));
        assert!(!looks(&sample()[..SIZE - 1]));
    }
}
