//! Tales of Symphonia (PC, Steam): `TOSSaveData0.dat`, a fixed 10,240-byte save with no
//! checksum the PC version checks.
//!
//! Layout (little-endian), from public notes on the save format (facts): game time in
//! frames at 0x10 (60 a second), gald at 0x14 (copied at 0x1D0), records from 0x2C, nine
//! 0x118-byte character records from 0x548 (Lloyd, Colette, Genis, Raine, Sheena, Zelos,
//! Presea, Regal, Kratos), the party at 0x111D, one byte per item from 0x112E, and the grade
//! points (× 100) at 0x1D84.

use super::fields::{Builder, Checksum, Kind};
use crate::tree::TreeDoc;

pub const KIND: &str = "Tales of Symphonia save";
pub const SIZE: usize = 10240;
const CHARS: usize = 0x548;
const STRIDE: usize = 0x118;
const ITEMS: usize = 0x112E;
const NAMES: [&str; 9] = ["Lloyd", "Colette", "Genis", "Raine", "Sheena", "Zelos", "Presea", "Regal", "Kratos"];

fn u32_at(d: &[u8], at: usize) -> u32 {
    d.get(at..at + 4).map_or(0, |b| u32::from_le_bytes(b.try_into().unwrap()))
}

/// 10,240 bytes, nine characters with levels up to 250 and plausible gald and play time.
pub fn looks(d: &[u8]) -> bool {
    if d.len() != SIZE {
        return false;
    }
    let levels_ok = (0..9).all(|i| (1..=250).contains(&d[CHARS + i * STRIDE]));
    let exp_ok = (0..9).all(|i| u32_at(d, CHARS + i * STRIDE + 8) <= 99_999_999);
    levels_ok && exp_ok && u32_at(d, 0x14) <= 99_999_999 && u32_at(d, 0x14) == u32_at(d, 0x1D0)
}

pub fn parse(d: &[u8]) -> Result<TreeDoc, String> {
    if !looks(d) {
        return Err("not a Tales of Symphonia save".into());
    }
    let mut b = Builder::new(d);
    let g = "Party";
    b.ranged(&[g, "Gald"], 0x14, Kind::U32, 0, 99_999_999);
    b.mirror(&[g, "Gald"], 0x1D0);
    b.ranged(&[g, "Most gald held"], 0x30, Kind::U32, 0, 99_999_999);
    b.ranged(&[g, "Total gald spent"], 0x34, Kind::U32, 0, 4_000_000_000);
    b.ranged(&[g, "Times saved"], 0x38, Kind::U32, 0, 99_999);
    b.ranged(&[g, "Times the game was cleared"], 0x3C, Kind::U32, 0, 99);
    b.ranged(&[g, "Battles"], 0x54, Kind::U32, 0, 999_999);
    b.ranged(&[g, "Escapes"], 0x44, Kind::U32, 0, 999_999);
    b.ranged(&[g, "Grade points (stored x100)"], 0x1D84, Kind::U32, 0, 99_999_999);
    b.ranged(&[g, "Play time (frames, 60 a second)"], 0x10, Kind::U32, 0, 4_000_000_000);
    for (i, name) in NAMES.iter().enumerate() {
        let o = CHARS + i * STRIDE;
        let c = "Characters";
        b.ranged(&[c, name, "Level"], o, Kind::U8, 1, 250);
        b.ranged(&[c, name, "Experience"], o + 8, Kind::U32, 0, 99_999_999);
        b.ranged(&[c, name, "HP"], o + 22, Kind::U16, 0, 9999);
        b.ranged(&[c, name, "TP"], o + 24, Kind::U16, 0, 999);
        b.ranged(&[c, name, "Max HP"], o + 38, Kind::U16, 1, 9999);
        b.ranged(&[c, name, "Max TP"], o + 40, Kind::U16, 0, 999);
        for (label, off) in [("Strength", 42), ("Attack", 44), ("Attack 2", 46), ("Defense", 48), ("Luck", 50), ("Accuracy", 52), ("Evasion", 54), ("Intelligence", 56)] {
            b.ranged(&[c, name, label], o + off, Kind::U16, 0, 1999);
        }
        b.ranged(&[c, name, "Overlimit (%)"], o + 70, Kind::U8, 0, 100);
        b.ranged(&[c, name, "Affection"], o + 72, Kind::U16, 0, 9999);
    }
    for (i, name) in ITEM_NAMES.iter().enumerate() {
        b.ranged(&["Items", name], ITEMS + i, Kind::U8, 0, 20);
    }
    Ok(b.finish(KIND, Checksum::None).with_note("Close the game first. Item counts go up to 20; key items are single items. Techs, titles, recipes and the Collector's Book are not shown."))
}

